"""List every picture the game ships, with size and whether the code names it.

Run: python3 tools/build-asset-manifest.py
Writes garden/asset-manifest-data.mjs, which the studio's asset list reads.
A test checks the list still matches the files on disk, so rerun this after adding art.
"""
import json, re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art"
CODE = [p for ext in ("*.mjs", "*.js", "*.html", "*.css") for p in ROOT.glob(ext)] + \
       [p for d in ("garden", "ui", "core") for ext in ("*.mjs", "*.css") for p in (ROOT / d).glob(ext)]
CODE = [p for p in CODE if p.name not in ("asset-manifest-data.mjs",)]
text = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in CODE)

rows = []
for f in sorted(ART.rglob("*")):
    if f.suffix.lower() not in (".webp", ".png", ".jpg", ".jpeg", ".svg"):
        continue
    rel = f.relative_to(ROOT).as_posix()
    try:
        w, h = Image.open(f).size
    except Exception:
        w = h = 0
    rows.append({"p": rel, "w": w, "h": h, "b": f.stat().st_size, "u": 1 if rel in text else 0})
(ROOT / "garden/asset-manifest-data.mjs").write_text(
    "// Generated by tools/build-asset-manifest.py. Do not edit by hand.\n"
    "// p = path, w/h = size in pixels, b = bytes, u = 1 when the code names the file.\n"
    "export const ASSET_MANIFEST = " + json.dumps(rows, separators=(",", ":")) + ";\n", encoding="utf-8")
print(len(rows), "pictures,", sum(r["u"] for r in rows), "named in code")
