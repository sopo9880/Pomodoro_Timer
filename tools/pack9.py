"""Monuments (D2), weekday badges and share frames (D3), extra celebration pieces (C3).

Run: python3 tools/pack9.py <folder with the chosen pack-3 sheets>
Writes assets/art/world/monuments, assets/art/ui/badges, assets/art/ui/share,
assets/art/ui/fx/pack3 and garden/pack3-art-data.mjs.
"""
import glob, json, sys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from keyer import key, parts

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art"
SRC = Path(sys.argv[1])


def tight(a, thr=20):
    ys, xs = np.where(a[..., 3] > thr)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def save(a, rel, max_w):
    im = Image.fromarray(tight(a))
    if im.width > max_w:
        im = im.resize((max_w, max(1, round(im.height * max_w / im.width))), Image.LANCZOS)
    p = ART / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    im.save(p, "WEBP", quality=90, method=6)
    return {"src": f"assets/art/{rel}?v=1", "w": im.width, "h": im.height}


def sheet(h, min_area):
    return parts(key(next(iter(glob.glob(str(SRC / f"*{h}*.jpg"))))), min_area=min_area)


data = {}
ps = sheet("1589d0de", 6000)
assert len(ps) == 4
data["monuments"] = {sid: save(p["img"], f"world/monuments/{sid}.webp", 420)
                     for sid, p in zip(("stele", "signpost-arch", "cairn", "rose-arch"), ps)}
ps = sheet("b63f13ef", 3000)
assert len(ps) == 9
data["badges"] = [save(p["img"], f"ui/badges/day_{i}.webp", 160) for i, p in enumerate(ps[:7])]
data["frames"] = [save(p["img"], f"ui/share/frame_{i}.webp", 900) for i, p in enumerate(ps[7:])]
ps = sheet("20a57f22", 500)
data["extras"] = [save(p["img"], f"ui/fx/pack3/x_{i:02d}.webp", 192) for i, p in enumerate(ps)]
(ROOT / "garden/pack3-art-data.mjs").write_text(
    "// Generated by tools/pack9.py from the prompt-pack-3 sheets. Do not edit by hand.\n"
    "export const PACK3_ART = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print({k: len(v) for k, v in data.items()})
