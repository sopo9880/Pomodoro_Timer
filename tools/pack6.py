"""Back views of placeable furniture from the prompt-pack-3 sheets (E1a, E1b).

Run: python3 tools/pack6.py <folder with the chosen pack-3 sheets>
Each back view is fitted onto the size of the front art it pairs with (bottom-centred),
so swapping views never moves the object. Writes assets/art/world/decor_back/ and
garden/decor-back-data.mjs.
"""
import glob, json, sys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from keyer import key, parts

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art/world"
SRC = Path(sys.argv[1])
L = "landmarks/"
# sheet hash -> [(sprite, front art)], in the order the parts come out of the sheet
SHEETS = {
    "d1d00ede": [("wooden-bench", L + "central_garden/prop_02.webp"), ("star-bench", L + "starry_hill/prop_03.webp"),
                 ("tea-table", L + "forest_library/prop_06.webp"), ("wooden-fence", L + "central_garden/prop_04.webp")],
    "40639990": [("flower-archway", L + "decor_01/prop_07.webp"), ("birdhouse", L + "decor_01/prop_05.webp"),
                 ("mailbox", "decor/mailbox.webp"), ("garden-swing", "decor/garden_swing.webp")],
}


def tight(a, thr=20):
    ys, xs = np.where(a[..., 3] > thr)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


data = {}
for h, items in SHEETS.items():
    ps = parts(key(next(iter(glob.glob(str(SRC / f"*{h}*.jpg"))))), min_area=8000)
    assert len(ps) == len(items), f"{h}: expected {len(items)} objects, got {len(ps)}"
    for p, (sprite, front) in zip(ps, items):
        f = Image.open(ART / front).convert("RGBA")
        back = tight(p["img"])
        s = (f.width / back.shape[1] + f.height / back.shape[0]) / 2
        im = Image.fromarray(back).resize((max(1, round(back.shape[1] * s)), max(1, round(back.shape[0] * s))), Image.LANCZOS)
        canvas = Image.new("RGBA", f.size, (0, 0, 0, 0))
        canvas.alpha_composite(im, (max(0, (f.width - im.width) // 2), max(0, f.height - im.height)))
        rel = f"decor_back/{sprite}.webp"
        (ART / rel).parent.mkdir(parents=True, exist_ok=True)
        canvas.save(ART / rel, "WEBP", quality=92, method=6)
        data[sprite] = f"assets/art/world/{rel}?v=1"
(ROOT / "garden/decor-back-data.mjs").write_text(
    "// Generated by tools/pack6.py from the prompt-pack-3 sheets. Do not edit by hand.\n"
    "export const DECOR_BACK_DATA = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print(sorted(data))
