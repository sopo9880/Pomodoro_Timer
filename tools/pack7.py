"""World dressing from the prompt-pack-3 sheets: pond edge (B2) and ground decals (B3).

Run: python3 tools/pack7.py <folder with the chosen pack-3 sheets>
Each sheet is a grid; every row is one kind. Writes assets/art/world/pond and
assets/art/world/decals plus garden/world-art-data.mjs.
"""
import glob, json, sys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from keyer import key, parts

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art/world"
SRC = Path(sys.argv[1])


def rows_of(ps, gap=.5):
    ps = sorted(ps, key=lambda p: (p["box"][1] + p["box"][3]) / 2)
    rows = []
    for p in ps:
        cy = (p["box"][1] + p["box"][3]) / 2; h = p["box"][3] - p["box"][1]
        if rows and abs(cy - rows[-1]["cy"]) < gap * max(h, rows[-1]["h"]):
            rows[-1]["items"].append(p)
            rows[-1]["cy"] = np.mean([(q["box"][1] + q["box"][3]) / 2 for q in rows[-1]["items"]])
        else:
            rows.append({"cy": cy, "h": h, "items": [p]})
    return [sorted(r["items"], key=lambda p: p["box"][0]) for r in rows]


def tight(a, thr=20):
    ys, xs = np.where(a[..., 3] > thr)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def save(a, rel, max_w):
    im = Image.fromarray(tight(a))
    if im.width > max_w:
        im = im.resize((max_w, max(1, round(im.height * max_w / im.width))), Image.LANCZOS)
    p = ART / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    im.save(p, "WEBP", quality=90, method=6)
    return {"src": f"assets/art/world/{rel}?v=1", "w": im.width, "h": im.height}


def sheet(h, min_area):
    return parts(key(next(iter(glob.glob(str(SRC / f"*{h}*.jpg"))))), min_area=min_area)


data = {"pond": {}, "decals": {}}
r = rows_of(sheet("d62aabe0", 1200))
assert len(r) == 4, f"pond sheet rows: {len(r)}"
for kind, row in zip(("reed", "lily", "ripple", "glint"), r):
    data["pond"][kind] = [save(p["img"], f"pond/{kind}_{i}.webp", 256) for i, p in enumerate(row)]
ps = sheet("b94419da", 600)
cuts = (200, 380, 580)  # the leaf row is a loose scatter, so rows are split by height
r = [sorted([p for p in ps if lo <= (p["box"][1] + p["box"][3]) / 2 < hi], key=lambda p: p["box"][0])
     for lo, hi in zip((0,) + cuts, cuts + (10000,))]
assert all(len(row) >= 4 for row in r), [len(x) for x in r]
for kind, row in zip(("flowers", "pebbles", "tufts", "leaves"), r):
    data["decals"][kind] = [save(p["img"], f"decals/{kind}_{i}.webp", 160) for i, p in enumerate(row)]
# B4: region props, numbered in reading order (the zone each one dresses is decided in garden/scenery.mjs)
ps = sorted(sheet("a503b794", 600), key=lambda p: (p["box"][1] // 120, p["box"][0]))
assert len(ps) == 45, f"props: {len(ps)}"
data["props"] = [save(p["img"], f"props2/p_{i:02d}.webp", 256) for i, p in enumerate(ps)]
(ROOT / "garden/world-art-data.mjs").write_text(
    "// Generated by tools/pack7.py from the prompt-pack-3 sheets. Do not edit by hand.\n"
    "export const WORLD_ART = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print({k: (len(v) if isinstance(v, list) else {kk: len(vv) for kk, vv in v.items()}) for k, v in data.items()})
