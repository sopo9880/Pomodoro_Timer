"""Rare creatures (D1) from the prompt-pack-3 sheet.

Run: python3 tools/pack8.py <folder with the chosen pack-3 sheets>
Each creature has two walking frames; they become the usual 4-frame strip
(0,1,0,1) bottom-centred on one canvas, plus a codex picture.
Writes assets/art/wildlife/<id>/ and garden/rare-art-data.mjs.
"""
import glob, json, sys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from keyer import key, parts

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets/art/wildlife"
SRC = Path(sys.argv[1])
SPECIES = ["white-fawn", "moon-rabbit", "golden-chick", "blue-newt"]
MAX_H = 200


def tight(a, thr=20):
    ys, xs = np.where(a[..., 3] > thr)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


ps = parts(key(next(iter(glob.glob(str(SRC / "*1614b2b2*.jpg"))))), min_area=3000)
assert len(ps) == 8, f"expected 8 frames, got {len(ps)}"
data = {}
for k, sid in enumerate(SPECIES):
    frames = [tight(ps[2 * k]["img"]), tight(ps[2 * k + 1]["img"])]
    s = MAX_H / max(f.shape[0] for f in frames)
    s = min(s, 1.0) if max(f.shape[1] for f in frames) * s <= 260 else 260 / max(f.shape[1] for f in frames)
    ims = [Image.fromarray(f).resize((max(1, round(f.shape[1] * s)), max(1, round(f.shape[0] * s))), Image.LANCZOS) for f in frames]
    W, H = max(i.width for i in ims) + 4, max(i.height for i in ims) + 2
    strip = Image.new("RGBA", (W * 4, H), (0, 0, 0, 0))
    for n, im in enumerate([ims[0], ims[1], ims[0], ims[1]]):
        strip.alpha_composite(im, (n * W + (W - im.width) // 2, H - im.height))
    d = OUT / sid
    d.mkdir(parents=True, exist_ok=True)
    strip.save(d / "frames.webp", "WEBP", quality=90, method=6)
    ims[0].save(d / "codex.webp", "WEBP", quality=90, method=6)
    data[sid] = {"frames": f"assets/art/wildlife/{sid}/frames.webp", "count": 4, "frameWidth": W, "frameHeight": H,
                 "codex": f"assets/art/wildlife/{sid}/codex.webp", "ref": ims[0].height}
(ROOT / "garden/rare-art-data.mjs").write_text(
    "// Generated by tools/pack8.py from the prompt-pack-3 sheets. Do not edit by hand.\n"
    "export const RARE_WILDLIFE_ART = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print({k: (v["frameWidth"], v["frameHeight"], v["ref"]) for k, v in data.items()})
